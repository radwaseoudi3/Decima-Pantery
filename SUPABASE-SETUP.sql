grant select, update on public.pantry_orders to authenticated;
grant execute on function public.place_pantry_order(text,integer,integer,text,text,text) to anon, authenticated;
grant execute on function public.pantry_is_admin() to authenticated;
grant execute on function public.pantry_is_staff() to authenticated;
