-- Atomic public order function. Employees do not need a login.
-- It validates stock, subtracts recipe quantities, treats each sugar spoon as 5 grams,
-- and inserts the shared order in one database transaction.
create or replace function public.place_pantry_order(
  p_drink_id text,
  p_quantity integer,
  p_sugar_spoons integer,
  p_location_id text,
  p_desk_id text default null,
  p_custom_location text default null,
  p_custom_request text default null
)
returns public.pantry_orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_drink public.pantry_drinks%rowtype;
  v_location public.pantry_locations%rowtype;
  v_order public.pantry_orders%rowtype;
  v_ing jsonb;
  v_amount numeric;
  v_material_id text;
  v_sugar_id text;
  v_name_en text;
  v_name_ar text;
  v_icon text;
begin
  if p_quantity is null or p_quantity < 1 or p_quantity > 10 then
    raise exception 'invalid_quantity';
  end if;
  if p_sugar_spoons is null or p_sugar_spoons < 0 or p_sugar_spoons > 10 then
    raise exception 'invalid_sugar';
  end if;

  if p_location_id = '__custom_location__' then
    if coalesce(trim(p_custom_location),'') = '' then raise exception 'custom_location_required'; end if;
    v_location.id := '__custom_location__';
    v_location.name_en := trim(p_custom_location);
    v_location.name_ar := 'موقع مخصص: ' || trim(p_custom_location);
    v_location.has_desk_map := false;
    v_location.active := true;
  else
    select * into v_location from public.pantry_locations where id = p_location_id and active = true;
    if not found then raise exception 'invalid_location'; end if;
    if v_location.has_desk_map and coalesce(trim(p_desk_id),'') = '' then raise exception 'desk_required'; end if;
  end if;

  if p_drink_id = '__custom__' then
    if coalesce(trim(p_custom_request),'') = '' then raise exception 'custom_request_required'; end if;
    v_name_en := 'Custom Request';
    v_name_ar := 'طلب خاص';
    v_icon := '✍️';
    p_sugar_spoons := 0;
  else
    select * into v_drink from public.pantry_drinks where id = p_drink_id and active = true;
    if not found then raise exception 'invalid_drink'; end if;
    v_name_en := v_drink.name_en;
    v_name_ar := v_drink.name_ar;
    v_icon := v_drink.icon;

    for v_ing in select value from jsonb_array_elements(v_drink.ingredients)
    loop
      v_material_id := v_ing->>'materialId';
      v_amount := coalesce((v_ing->>'amount')::numeric,0) * p_quantity;
      update public.pantry_materials
      set current_quantity = current_quantity - v_amount
      where id = v_material_id and active = true and current_quantity >= v_amount;
      if not found then raise exception 'insufficient_stock:%', v_material_id; end if;
    end loop;

    if p_sugar_spoons > 0 then
      select id into v_sugar_id from public.pantry_materials
      where active = true and base_unit = 'Gram' and (id = 'sugar' or lower(name_en) = 'sugar')
      order by case when id='sugar' then 0 else 1 end limit 1;
      if v_sugar_id is null then raise exception 'sugar_not_found'; end if;
      v_amount := p_sugar_spoons * 5 * p_quantity;
      update public.pantry_materials
      set current_quantity = current_quantity - v_amount
      where id = v_sugar_id and current_quantity >= v_amount;
      if not found then raise exception 'insufficient_stock:sugar'; end if;
    end if;
  end if;

  insert into public.pantry_orders(
    drink_id,drink_name_en,drink_name_ar,drink_icon,
    location_id,location_name_en,location_name_ar,desk_id,
    quantity,sugar_spoons,custom_request,status
  ) values (
    p_drink_id,v_name_en,v_name_ar,v_icon,
    v_location.id,v_location.name_en,v_location.name_ar,nullif(trim(p_desk_id),''),
    p_quantity,p_sugar_spoons,nullif(trim(p_custom_request),''),'New'
  ) returning * into v_order;

  return v_order;
end;
$$;

