create or replace function public.pantry_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.pantry_staff
    where lower(email) = lower(coalesce(auth.jwt()->>'email','')) and role = 'admin'
  );
$$;

create or replace function public.pantry_is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.pantry_staff
    where lower(email) = lower(coalesce(auth.jwt()->>'email','')) and role in ('admin','barista')
  );
$$;

create table if not exists public.pantry_materials (
  id text primary key,
  name_en text not null,
  name_ar text not null,
  base_unit text not null check (base_unit in ('Gram','Milliliter','Piece')),
  package_name text not null default 'Pack',
  units_per_package numeric not null default 1 check (units_per_package > 0),
  current_quantity numeric not null default 0 check (current_quantity >= 0),
  minimum_quantity numeric not null default 0 check (minimum_quantity >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.pantry_drinks (
  id text primary key,
  name_en text not null,
  name_ar text not null,
  icon text not null default '☕',
  category text not null default 'Drink',
  description text not null default '',
  ingredients jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.pantry_locations (
  id text primary key,
  name_en text not null,
  name_ar text not null,
  has_desk_map boolean not null default false,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.pantry_orders (
  id text primary key default gen_random_uuid()::text,
  number bigint generated by default as identity unique,
  drink_id text not null,
  drink_name_en text not null,
  drink_name_ar text not null,
  drink_icon text not null default '☕',
  location_id text not null,
  location_name_en text not null,
  location_name_ar text not null,
  desk_id text,
  quantity integer not null check (quantity between 1 and 10),
  sugar_spoons integer not null default 0 check (sugar_spoons between 0 and 10),
  custom_request text,
  status text not null default 'New' check (status in ('New','Preparing','Completed')),
  created_at timestamptz not null default now(),
  accepted_at timestamptz,
  completed_at timestamptz
);

alter table public.pantry_orders alter column number restart with 1001;

