-- Re-running this file safely replaces policies.
drop policy if exists pantry_materials_read on public.pantry_materials;
drop policy if exists pantry_materials_admin on public.pantry_materials;
drop policy if exists pantry_drinks_read on public.pantry_drinks;
drop policy if exists pantry_drinks_admin on public.pantry_drinks;
drop policy if exists pantry_locations_read on public.pantry_locations;
drop policy if exists pantry_locations_admin on public.pantry_locations;
drop policy if exists pantry_orders_staff_read on public.pantry_orders;
drop policy if exists pantry_orders_staff_update on public.pantry_orders;

create policy pantry_materials_read on public.pantry_materials for select to anon, authenticated using (true);
create policy pantry_materials_admin on public.pantry_materials for all to authenticated using (public.pantry_is_admin()) with check (public.pantry_is_admin());
create policy pantry_drinks_read on public.pantry_drinks for select to anon, authenticated using (true);
create policy pantry_drinks_admin on public.pantry_drinks for all to authenticated using (public.pantry_is_admin()) with check (public.pantry_is_admin());
create policy pantry_locations_read on public.pantry_locations for select to anon, authenticated using (true);
create policy pantry_locations_admin on public.pantry_locations for all to authenticated using (public.pantry_is_admin()) with check (public.pantry_is_admin());
create policy pantry_orders_staff_read on public.pantry_orders for select to authenticated using (public.pantry_is_staff());
create policy pantry_orders_staff_update on public.pantry_orders for update to authenticated using (public.pantry_is_staff()) with check (public.pantry_is_staff());

grant usage on schema public to anon, authenticated;
grant select on public.pantry_materials, public.pantry_drinks, public.pantry_locations to anon, authenticated;
